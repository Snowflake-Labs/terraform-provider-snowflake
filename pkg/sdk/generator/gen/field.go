package gen

import (
	"fmt"
	"slices"
	"strings"

	"github.com/Snowflake-Labs/terraform-provider-snowflake/pkg/internal/collections"
)

// Field defines properties of a single field or struct (by defining Fields)
type Field struct {
	// Parent allows to traverse fields hierarchy more easily, nil for root
	Parent *Field
	// Fields defines children, use for struct fields
	Fields []Field
	// Validations defines validations on given field level (e.g. oneOf for children)
	Validations []*Validation
	// Name is how field is called in parent struct
	Name string
	// Kind is fields type (e.g. string, *bool)
	Kind string
	// Tags should contain ddl and sql tags used for SQL generation
	Tags map[string][]string
	// Required is used to mark fields which are essential (it's used e.g. for DTO builders generation)
	Required bool
	// IsEmptyStruct marks fields created via QueryStruct composition which are empty structs
	IsEmptyStruct bool
	// IsShared marks fields whose struct types are generated by a different object definition.
	// The struct, Request type, and constructor are not generated for this object; the toOpts
	// mapping calls the shared struct's standalone toOpts() method instead of inlining.
	IsShared bool
	// GenerateSharedToOpts marks that a standalone toOpts() method should be generated for this struct.
	GenerateSharedToOpts bool
	// SetParameters and UnsetParameters generate the SetParameterFromRaw/UnsetParameterFromRaw
	// writers on this struct's Request type, scoped to these parameters.
	SetParameters   []ParameterField
	UnsetParameters []ParameterField
}

// ParameterField is a catalog parameter recorded on a struct. Parser is resolved from the kind once
// at build time (see InfoForKind), so templates carry no kind logic. Unused for unset.
type ParameterField struct {
	SqlName   string
	FieldName string
	Parser    string
}

func NewField(name string, kind string, tagBuilder *TagBuilder, transformer FieldTransformer) *Field {
	var tags map[string][]string
	if tagBuilder != nil {
		tags = tagBuilder.Build()
	} else {
		tags = make(map[string][]string)
	}
	f := &Field{
		Name: name,
		Kind: kind,
		Tags: tags,
	}
	if !IsNil(transformer) {
		return transformer.Transform(f)
	}
	return f
}

func (f *Field) withField(field *Field) *Field {
	f.Fields = append(f.Fields, *field)
	return f
}

func (f *Field) withFields(fields ...*Field) *Field {
	for _, field := range fields {
		f.Fields = append(f.Fields, *field)
	}
	return f
}

func (f *Field) withValidations(validations ...*Validation) *Field {
	f.Validations = validations
	return f
}

// HasAnyValidationInSubtree checks if any validations are present from current field level downwards
func (f *Field) HasAnyValidationInSubtree() bool {
	if len(f.Validations) > 0 {
		return true
	}
	for _, f := range f.Fields {
		if f.HasAnyValidationInSubtree() {
			return true
		}
	}
	return false
}

// TagsPrintable defines how tags are printed in options structs, it ensures the same order of tags for every field
func (f *Field) TagsPrintable() string {
	tagNames := []string{"ddl", "sql", "db"}
	var tagParts []string
	for _, tagName := range tagNames {
		v, ok := f.Tags[tagName]
		if ok {
			tagParts = append(tagParts, fmt.Sprintf(`%s:"%s"`, tagName, strings.Join(v, ",")))
		}
	}
	if len(tagParts) > 0 {
		return fmt.Sprintf("`%s`", strings.Join(tagParts, " "))
	}
	return ""
}

// KindNoPtr return field's Kind but without pointer and array
func (f *Field) KindNoPtr() string {
	kindWithoutPtr, _ := strings.CutPrefix(f.Kind, "*")
	kindWithoutPtr, _ = strings.CutPrefix(kindWithoutPtr, "[]")
	return kindWithoutPtr
}

// KindNoSlice return field's Kind but without array
func (f *Field) KindNoSlice() string {
	kindWithoutSlice, _ := strings.CutPrefix(f.Kind, "[]")
	return kindWithoutSlice
}

// IsStruct checks if field is a struct
func (f *Field) IsStruct() bool {
	return f.HasAnyFields() || f.IsEmptyStruct
}

func (f *Field) HasAnyFields() bool {
	return len(f.Fields) > 0
}

func (f *Field) IsPointer() bool {
	return strings.HasPrefix(f.Kind, "*")
}

func (f *Field) IsSlice() bool {
	return strings.HasPrefix(f.Kind, "[]")
}

// SliceElemVar returns a loop variable name derived from the field name.
// E.g. "Arguments" -> "argument", "Columns" -> "column", "On" -> "on".
func (f *Field) SliceElemVar() string {
	name := strings.ToLower(f.Name[:1]) + f.Name[1:]
	name, _ = strings.CutSuffix(name, "s")
	return name
}

// SliceIndexVar is the for-loop index next to SliceElemVar (e.g. "argumentIdx").
// Nested slices each get their own; do not reuse toOpts' constant "i".
func (f *Field) SliceIndexVar() string {
	return f.SliceElemVar() + "Idx"
}

// NeedsSliceIndexVar reports whether the validate() loop must bind SliceIndexVar.
// False for ValidIdentifier-only subtrees so the index is not an unused variable.
func (f *Field) NeedsSliceIndexVar() bool {
	for _, v := range f.Validations {
		if v.hasIndexedErrorPath() {
			return true
		}
	}
	for i := range f.Fields {
		if f.Fields[i].NeedsSliceIndexVar() {
			return true
		}
	}
	return false
}

// ShouldBeInDto checks if field is not some static SQL field which should not be interacted with by SDK user
// TODO: this is a very naive implementation, consider fixing it with DSL builder connection
func (f *Field) ShouldBeInDto() bool {
	return !slices.Contains(f.Tags["ddl"], "static") && !f.IsEmptyStruct
}

// IsRoot checks if field is at the top of field hierarchy, basically it is true for Option structs
func (f *Field) IsRoot() bool {
	return f.Parent == nil
}

// Path returns the way through the tree to the top, with dot separator (e.g. .SomeField.SomeChild)
func (f *Field) Path() string {
	if f.IsRoot() {
		return ""
	} else {
		return fmt.Sprintf("%s.%s", f.Parent.Path(), f.Name)
	}
}

// AccessExpr is the Go expression to read this field in a validate() body.
// Drop-in for today's `opts` + Path(). When a slice ancestor exists, the path is relative
// to that slice's loop variable (SliceElemVar), not to opts.
func (f *Field) AccessExpr() string {
	if f.hasSliceAncestor() {
		anc := f.sliceAncestor()
		return anc.SliceElemVar() + strings.TrimPrefix(f.Path(), anc.Path())
	}
	return "opts" + f.Path()
}

// IndexedPath is Path with a [0] inserted after every slice ancestor, so a field reached through
// a slice addresses its single generated element (e.g. .Arguments[0].ArgDataType).
func (f *Field) IndexedPath() string {
	if f.IsRoot() {
		return ""
	}
	return fmt.Sprintf("%s.%s", f.Parent.IndexedElemPath(), f.Name)
}

// IndexedElemPath is IndexedPath with a trailing [0] appended when f itself is a slice.
func (f *Field) IndexedElemPath() string {
	return f.IndexedElemPathAt(0)
}

// IndexedElemPathAt is IndexedPath with a trailing [i] appended when f itself is a slice.
// Ancestor slices stay [0] (same as IndexedPath). Used to assign through a second element
// in BothInvalid unit-test DefaultModify.
func (f *Field) IndexedElemPathAt(i int) string {
	if f.IsSlice() {
		return f.IndexedPath() + fmt.Sprintf("[%d]", i)
	}
	return f.IndexedPath()
}

// PathWithRoot returns the way through the tree to the top, with dot separator and root included (e.g. Struct.SomeField.SomeChild)
func (f *Field) PathWithRoot() string {
	if f.IsRoot() {
		return f.Name
	} else {
		return fmt.Sprintf("%s.%s", f.Parent.PathWithRoot(), f.Name)
	}
}

// PathWithRootExpr is the Go expression for PathWithRoot in a validate() body
// (quoted literal, or fmt.Sprintf inserting each slice's SliceIndexVar).
func (f *Field) PathWithRootExpr() string {
	var indexVars []string
	format := f.pathWithRootIndexed(func(seg *Field) string {
		indexVars = append(indexVars, seg.SliceIndexVar())
		return "[%d]"
	})
	if len(indexVars) == 0 {
		return fmt.Sprintf("%q", format)
	}
	return fmt.Sprintf("fmt.Sprintf(%q, %s)", format, strings.Join(indexVars, ", "))
}

// PathWithRootForTest is PathWithRoot with concrete indexes after every slice.
// failingSlice (if on the path) uses [failingIndex]; every other slice uses [0].
// Pass failingSlice == nil for all [0].
func (f *Field) PathWithRootForTest(failingSlice *Field, failingIndex int) string {
	return f.pathWithRootIndexed(func(seg *Field) string {
		idx := 0
		if failingSlice != nil && seg == failingSlice {
			idx = failingIndex
		}
		return fmt.Sprintf("[%d]", idx)
	})
}

func (f *Field) pathFromRoot() []*Field {
	return append(f.AncestorsFromRoot(), f)
}

func (f *Field) pathWithRootIndexed(sliceSuffix func(*Field) string) string {
	var b strings.Builder
	for i, seg := range f.pathFromRoot() {
		if i > 0 {
			b.WriteByte('.')
		}
		b.WriteString(seg.Name)
		if seg.IsSlice() {
			b.WriteString(sliceSuffix(seg))
		}
	}
	return b.String()
}

// DtoKind returns what should be fields kind in generated DTO, because it may differ from Kind
func (f *Field) DtoKind() string {
	switch {
	case f.IsRoot():
		withoutSuffix, _ := strings.CutSuffix(f.Kind, "Options")
		return fmt.Sprintf("%sRequest", withoutSuffix)
	case f.IsStruct():
		return fmt.Sprintf("%sRequest", f.Kind)
	default:
		return f.Kind
	}
}

// IsIdentifier reports whether this field has ddl:"identifier" tag.
func (f *Field) IsIdentifier() bool {
	return slices.Contains(f.Tags["ddl"], "identifier")
}

// SlugPath returns the field's path in the underscore-separated form with the root rendered as "opts"
// (e.g. root -> "opts", ".Set.MinNodes" -> "opts_Set_MinNodes"). Unlike Path(), it never returns an empty string.
func (f *Field) SlugPath() string {
	if f.IsRoot() {
		return "opts"
	}
	return f.Parent.SlugPath() + "_" + f.Name
}

// FindChild returns the direct child field with the given name, or nil if none exists.
func (f *Field) FindChild(name string) *Field {
	el, err := collections.FindFirst(f.Fields, func(f Field) bool {
		return f.Name == name
	})
	if err != nil {
		return nil
	}
	return el
}

// FindChildCaseInsensitive returns the direct child field whose name matches case-insensitively, or nil if none exists.
func (f *Field) FindChildCaseInsensitive(name string) *Field {
	el, err := collections.FindFirst(f.Fields, func(f Field) bool {
		return strings.EqualFold(f.Name, name)
	})
	if err != nil {
		return nil
	}
	return el
}

// AncestorsFromRoot returns this field's ancestors ordered from the root down to (but not including) the field itself.
// Use to derive the priming statements needed before given field can be reached
// (e.g. opts.Set = &FunctionSet{} before opts.Set.Comment can be checked).
func (f *Field) AncestorsFromRoot() []*Field {
	if f.IsRoot() {
		return nil
	}
	return append(f.Parent.AncestorsFromRoot(), f.Parent)
}

// DtoDecl returns how struct should be declared in generated DTO (e.g. definition is without a pointer)
func (f *Field) DtoDecl() string {
	switch {
	case f.Parent == nil:
		withoutSuffix, _ := strings.CutSuffix(f.KindNoPtr(), "Options")
		return fmt.Sprintf("%sRequest", strings.ToUpper(withoutSuffix[:1])+withoutSuffix[1:])
	case f.IsStruct():
		return fmt.Sprintf("%sRequest", f.KindNoPtr())
	default:
		return f.KindNoPtr()
	}
}
